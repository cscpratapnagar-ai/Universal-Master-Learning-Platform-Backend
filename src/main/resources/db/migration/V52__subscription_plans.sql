CREATE TABLE IF NOT EXISTS subscription_plans (
    id UUID PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    monthly_price NUMERIC(12,2) NOT NULL DEFAULT 0,
    yearly_price NUMERIC(12,2) NOT NULL DEFAULT 0,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_subscription_plans_prices_non_negative CHECK (monthly_price >= 0 AND yearly_price >= 0)
);

CREATE TABLE IF NOT EXISTS subscription_plan_features (
    id UUID PRIMARY KEY,
    plan_id UUID NOT NULL REFERENCES subscription_plans(id) ON DELETE CASCADE,
    feature_code VARCHAR(80) NOT NULL,
    feature_value VARCHAR(200),
    UNIQUE(plan_id, feature_code)
);

CREATE INDEX IF NOT EXISTS idx_subscription_plans_active
    ON subscription_plans(active);
CREATE INDEX IF NOT EXISTS idx_subscription_plan_features_plan
    ON subscription_plan_features(plan_id);

